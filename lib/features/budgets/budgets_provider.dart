import 'package:flutter/material.dart';
import 'package:nabd/features/transactions/models/transaction_model.dart';
import 'package:uuid/uuid.dart';
import 'package:nabd/features/budgets/models/budget_model.dart';
import 'package:nabd/services/database_service.dart';
import 'package:nabd/features/categories/models/category_model.dart';

class BudgetsProvider extends ChangeNotifier {
  final DatabaseService _dbService;
  List<Budget> _budgets = [];
  List<Category> _categories = [];
  bool _isLoading = false;
  String? _error;
  bool _isInitialized = false;

  BudgetsProvider() : _dbService = DatabaseService() {
    _initialize();
  }

  // Public getters
  List<Budget> get budgets => List.unmodifiable(_budgets);
  bool get isLoading => _isLoading;
  String? get error => _error;
  bool get isInitialized => _isInitialized;

  Future<void> _initialize() async {
    try {
      await loadBudgets();
      _isInitialized = true;
      notifyListeners();
    } catch (e) {
      _setError('Failed to initialize budgets: $e');
    }
  }

  Future<void> loadBudgets() async {
    if (_isLoading) return;
    _setLoading(true);
    try {
      // Load categories first if not already loaded
      if (_categories.isEmpty) {
        _categories = await _dbService.getCategories();
      }
      
      final rawBudgets = await _dbService.getBudgets();
      _budgets = rawBudgets.map((b) {
        if (b.categoryId == null) {
          return b.copyWith(category: null);
        }
        
        // Find the category, or use null if not found
        final category = _categories.firstWhere(
          (c) => c.id == b.categoryId,
          orElse: () => Category(
            id: b.categoryId!,
            name: 'فئة غير معروفة',
            icon: Icons.error_outline,
            color: Colors.grey,
            type: TransactionType.expense,
          ),
        );
        
        return b.copyWith(category: category);
      }).toList();
      
      // If no budgets exist, create default ones for expense categories
      if (_budgets.isEmpty) {
        final expenseCategories = _categories
            .where((c) => c.type == TransactionType.expense)
            .toList();
            
        final now = DateTime.now();
        final firstDayOfMonth = DateTime(now.year, now.month, 1);
        final lastDayOfMonth = DateTime(now.year, now.month + 1, 0);
        
        for (final category in expenseCategories) {
          final budget = Budget(
            categoryId: category.id,
            category: category,
            totalAmount: 0.0, // Default to 0, user can update
            startDate: firstDayOfMonth,
            endDate: lastDayOfMonth,
            period: BudgetPeriod.monthly,
            receiveNotifications: true,
            notificationThreshold: 80.0,
            spentAmount: 0.0,
          );
          
          await _dbService.insertBudget(budget);
          _budgets.add(budget);
        }
      }
      
      _setError(null);
    } catch (e) {
      _setError('Failed to load budgets: $e');
      rethrow;
    } finally {
      _setLoading(false);
      notifyListeners();
    }
  }

  Future<bool> addBudget(Budget budget) async {
    try {
      await _dbService.insertBudget(budget);
      await loadBudgets();
      return true;
    } catch (e) {
      _setError('Failed to add budget: $e');
      return false;
    }
  }

  Future<bool> updateBudget(Budget budget) async {
    try {
      await _dbService.updateBudget(budget);
      await loadBudgets();
      return true;
    } catch (e) {
      _setError('Failed to update budget: $e');
      return false;
    }
  }

  Future<bool> deleteBudget(String id) async {
    try {
      await _dbService.deleteBudget(id);
      await loadBudgets();
      return true;
    } catch (e) {
      _setError('Failed to delete budget: $e');
      return false;
    }
  }

  // Get budget for a specific category
  Future<Budget?> getBudgetForCategory(String categoryId) async {
    try {
      // First, ensure budgets are loaded
      if (_budgets.isEmpty) {
        await loadBudgets();
      }
      
      // Try to find an existing budget for this category
      final existingBudget = _budgets.firstWhere(
        (b) => b.categoryId == categoryId,
        orElse: () => Budget(
          id: '', // Will be generated by database
          categoryId: categoryId,
          totalAmount: 0.0, // Default to 0, user can update
          startDate: DateTime.now(),
          endDate: DateTime.now().add(const Duration(days: 30)),
          period: BudgetPeriod.monthly,
          receiveNotifications: true,
          notificationThreshold: 80.0,
          spentAmount: 0.0,
        ),
      );
      
      // If we found an existing budget, return it
      if (existingBudget.id.isNotEmpty) {
        return existingBudget;
      }
      
      // Otherwise, create a new budget (this will be saved when the user updates it)
      return existingBudget;
    } catch (e) {
      debugPrint('Error getting budget for category $categoryId: $e');
      return null;
    }
  }

  // Add or update a budget for a category
  Future<void> addOrUpdateBudget({
    required String categoryId,
    required double amount,
    required BudgetPeriod period,
    bool receiveNotifications = true,
    double notificationThreshold = 80.0,
  }) async {
    try {
      final existingBudget = await getBudgetForCategory(categoryId);
      
      if (existingBudget != null && existingBudget.id.isNotEmpty) {
        // Update existing budget
        final updatedBudget = existingBudget.copyWith(
          totalAmount: amount,
          period: period,
          endDate: _calculateEndDate(DateTime.now(), period),
          receiveNotifications: receiveNotifications,
          notificationThreshold: notificationThreshold,
        );
        await updateBudget(updatedBudget);
      } else {
        // Create new budget
        final newBudget = Budget(
          categoryId: categoryId,
          totalAmount: amount,
          period: period,
          startDate: DateTime.now(),
          endDate: _calculateEndDate(DateTime.now(), period),
          receiveNotifications: receiveNotifications,
          notificationThreshold: notificationThreshold,
          spentAmount: 0.0,
        );
        await addBudget(newBudget);
      }
      
      _setError(null);
      await loadBudgets();
    } catch (e) {
      _setError('Failed to update budget: $e');
      rethrow;
    }
  }
  
  DateTime _calculateEndDate(DateTime startDate, BudgetPeriod period) {
    switch (period) {
      case BudgetPeriod.weekly:
        return startDate.add(const Duration(days: 7));
      case BudgetPeriod.monthly:
        final nextMonth = DateTime(startDate.year, startDate.month + 1, startDate.day);
        return nextMonth.isAfter(DateTime(startDate.year, startDate.month + 1, 1))
            ? DateTime(startDate.year, startDate.month + 2, 0)
            : nextMonth;
      case BudgetPeriod.yearly:
        return DateTime(startDate.year + 1, startDate.month, startDate.day);
      case BudgetPeriod.custom:
        return startDate.add(const Duration(days: 30));
    }
  }

  // Delete budget for a category
  Future<bool> deleteBudgetForCategory(String categoryId) async {
    try {
      final budget = await getBudgetForCategory(categoryId);
      if (budget != null && budget.id.isNotEmpty) {
        return await deleteBudget(budget.id);
      }
      return false;
    } catch (e) {
      _setError('Failed to delete budget: $e');
      return false;
    }
  }

  void clear() {
    _budgets.clear();
    _setError(null);
    notifyListeners();
  }

  void _setLoading(bool loading) {
    if (_isLoading != loading) {
      _isLoading = loading;
      // Schedule the notification for the next frame
      WidgetsBinding.instance.addPostFrameCallback((_) {
        notifyListeners();
      });
    }
  }

  void _setError(String? error) {
    if (_error != error) {
      _error = error;
      // Schedule the notification for the next frame
      WidgetsBinding.instance.addPostFrameCallback((_) {
        notifyListeners();
      });
    }
  }
}
